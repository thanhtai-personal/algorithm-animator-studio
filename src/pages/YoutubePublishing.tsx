import { ArrowLeft, CheckCircle2, ExternalLink, RefreshCcw, Upload, Youtube } from "lucide-react";
import { useEffect, useMemo, useState } from "react";
import { useNavigate } from "react-router-dom";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Switch } from "@/components/ui/switch";
import { Textarea } from "@/components/ui/textarea";
import { exchangeYoutubeCode, getYoutubeAuthUrl, getYoutubeConfig, getYoutubePlaylists, uploadYoutubeVideo, type YoutubeConfigStatus, type YoutubePlaylist, type YoutubeUploadForm, type YoutubeUploadResult } from "@/lib/youtubeApi";
import { getLastExportedVideo, type ExportedVideoAsset } from "@/lib/studioMediaRegistry";

const TOKEN_KEY = "algoshorts.youtube.refreshToken";
const DEFAULT_FORM: YoutubeUploadForm = {
  title: "Algorithm explained visually",
  description: "Visual explanation generated by AlgoShorts Studio.",
  tags: "algorithm, programming, visualization, code visual lab",
  categoryId: "27",
  privacyStatus: "unlisted",
  publishAt: "",
  playlistId: "",
  madeForKids: false,
  notifySubscribers: false,
  containsSyntheticMedia: true,
};

export default function YoutubePublishing() {
  const navigate = useNavigate();
  const [config, setConfig] = useState<YoutubeConfigStatus | null>(null);
  const [refreshToken, setRefreshToken] = useState(() => localStorage.getItem(TOKEN_KEY) || "");
  const [playlists, setPlaylists] = useState<YoutubePlaylist[]>([]);
  const [videoFile, setVideoFile] = useState<File | null>(null);
  const [lastExported, setLastExported] = useState<ExportedVideoAsset | null>(() => getLastExportedVideo());
  const [form, setForm] = useState<YoutubeUploadForm>(DEFAULT_FORM);
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<YoutubeUploadResult | null>(null);

  const selectedFile = videoFile ?? lastExported?.file ?? null;
  const canUpload = Boolean(selectedFile && refreshToken && config?.hasClientId && config?.hasClientSecret);
  const redirectUri = useMemo(() => `${window.location.origin}/youtube-publishing`, []);

  useEffect(() => { void bootstrap(); }, []);

  async function bootstrap() {
    try {
      const nextConfig = await getYoutubeConfig();
      setConfig(nextConfig);
      setForm((current) => ({ ...current, ...nextConfig.defaults, title: current.title || nextConfig.defaults.title }));
      await exchangeCodeIfNeeded();
      const token = localStorage.getItem(TOKEN_KEY) || refreshToken;
      if (token) await loadPlaylists(token);
    } catch (error) {
      toast.error(error instanceof Error ? error.message : "Không đọc được cấu hình YouTube.");
    }
  }

  async function exchangeCodeIfNeeded() {
    const params = new URLSearchParams(window.location.search);
    const code = params.get("code");
    if (!code) return;
    const auth = await exchangeYoutubeCode(code, redirectUri);
    if (!auth.refreshToken) throw new Error("Google không trả refresh token. Hãy revoke quyền cũ rồi cấp lại với prompt consent.");
    localStorage.setItem(TOKEN_KEY, auth.refreshToken);
    setRefreshToken(auth.refreshToken);
    window.history.replaceState({}, document.title, window.location.pathname);
    toast.success("Đã cấp quyền YouTube.");
  }

  async function connectYoutube() {
    setLoading(true);
    try {
      window.location.href = await getYoutubeAuthUrl(redirectUri);
    } catch (error) {
      toast.error(error instanceof Error ? error.message : "Không tạo được link OAuth.");
      setLoading(false);
    }
  }

  async function loadPlaylists(token = refreshToken) {
    if (!token) return setPlaylists([]);
    try {
      setPlaylists(await getYoutubePlaylists(token));
    } catch (error) {
      toast.error(error instanceof Error ? error.message : "Không tải được playlist.");
    }
  }

  async function upload() {
    if (!selectedFile) return toast.error("Chưa chọn video để đăng.");
    if (!refreshToken) return toast.error("Chưa cấp quyền YouTube.");
    setLoading(true);
    setResult(null);
    try {
      const next = await uploadYoutubeVideo(selectedFile, refreshToken, normalizeForm(form));
      setResult(next);
      toast.success(next.playlistWarning ? "Video đã đăng, nhưng playlist có cảnh báo." : "Đã upload YouTube.");
    } catch (error) {
      toast.error(error instanceof Error ? error.message : "Upload YouTube thất bại.");
    } finally {
      setLoading(false);
    }
  }

  function disconnect() {
    localStorage.removeItem(TOKEN_KEY);
    setRefreshToken("");
    setPlaylists([]);
    toast.info("Đã ngắt refresh token ở trình duyệt này.");
  }

  function useLatestExport() {
    const latest = getLastExportedVideo();
    setLastExported(latest);
    setVideoFile(null);
    if (!latest) toast.info("Chưa có video export trong phiên hiện tại.");
  }

  return (
    <div className="min-h-screen bg-background text-foreground">
      <header className="flex items-center gap-3 border-b border-border/40 px-6 py-5">
        <Button variant="outline" size="icon" onClick={() => navigate("/long-content")}><ArrowLeft className="h-4 w-4" /></Button>
        <div className="flex h-11 w-11 items-center justify-center rounded-xl bg-gradient-to-br from-red-500 to-amber-400">
          <Youtube className="h-6 w-6 text-slate-950" />
        </div>
        <div className="flex-1">
          <h1 className="text-xl font-bold">YouTube Publishing</h1>
          <p className="text-xs text-muted-foreground">Quản lý OAuth, playlist, metadata và upload video long 16:9 vừa export.</p>
        </div>
        <Button variant="outline" onClick={useLatestExport}><RefreshCcw className="mr-2 h-4 w-4" />Lấy video mới export</Button>
      </header>

      <main className="grid gap-4 p-4 xl:grid-cols-[360px_1fr]">
        <Card className="h-fit space-y-4 p-4">
          <h2 className="font-semibold">Kết nối YouTube</h2>
          <StatusRow label="Client ID" ok={Boolean(config?.hasClientId)} />
          <StatusRow label="Client Secret" ok={Boolean(config?.hasClientSecret)} />
          <StatusRow label="Refresh token" ok={Boolean(refreshToken)} />
          <div className="grid gap-2">
            <Button onClick={connectYoutube} disabled={loading || !config?.hasClientId || !config?.hasClientSecret}>Cấp quyền YouTube</Button>
            <Button variant="outline" onClick={() => loadPlaylists()} disabled={!refreshToken}>Tải playlist</Button>
            <Button variant="ghost" onClick={disconnect} disabled={!refreshToken}>Ngắt kết nối</Button>
          </div>
          <p className="text-xs text-muted-foreground">OAuth secret nằm ở server .env. Refresh token hiện lưu localStorage để tool local dùng nhanh.</p>
        </Card>

        <div className="space-y-4">
          <Card className="space-y-4 p-4">
            <h2 className="font-semibold">Video nguồn</h2>
            {lastExported ? <p className="text-sm text-emerald-300">Video mới export: {lastExported.fileName}</p> : <p className="text-sm text-muted-foreground">Chưa có video export trong phiên này.</p>}
            <label className="flex cursor-pointer items-center gap-2 rounded-lg border border-dashed border-border p-3 text-sm text-muted-foreground">
              <Upload className="h-4 w-4" /> Chọn file video khác (.mp4/.webm)
              <input type="file" accept="video/*" className="hidden" onChange={(event) => setVideoFile(event.target.files?.[0] ?? null)} />
            </label>
            {selectedFile ? <p className="text-xs text-muted-foreground">Đang chọn: {selectedFile.name} · {(selectedFile.size / 1024 / 1024).toFixed(1)} MB</p> : null}
          </Card>

          <Card className="space-y-4 p-4">
            <h2 className="font-semibold">Metadata đăng video</h2>
            <Field label="Title" value={form.title} onChange={(value) => setForm({ ...form, title: value })} />
            <div>
              <Label>Description</Label>
              <Textarea className="mt-2 min-h-32" value={form.description} onChange={(event) => setForm({ ...form, description: event.target.value })} />
            </div>
            <Field label="Tags" value={form.tags} onChange={(value) => setForm({ ...form, tags: value })} />
            <div className="grid gap-3 md:grid-cols-3">
              <Field label="Category ID" value={form.categoryId} onChange={(value) => setForm({ ...form, categoryId: value })} />
              <div>
                <Label>Privacy</Label>
                <Select value={form.privacyStatus} onValueChange={(value) => setForm({ ...form, privacyStatus: value })}>
                  <SelectTrigger className="mt-2"><SelectValue /></SelectTrigger>
                  <SelectContent>
                    <SelectItem value="private">Private</SelectItem>
                    <SelectItem value="unlisted">Unlisted</SelectItem>
                    <SelectItem value="public">Public</SelectItem>
                  </SelectContent>
                </Select>
              </div>
              <Field label="Publish at" type="datetime-local" value={form.publishAt || ""} onChange={(value) => setForm({ ...form, publishAt: value })} />
            </div>
            <div>
              <Label>Playlist</Label>
              <Select value={form.playlistId || "none"} onValueChange={(value) => setForm({ ...form, playlistId: value === "none" ? "" : value })}>
                <SelectTrigger className="mt-2"><SelectValue /></SelectTrigger>
                <SelectContent>
                  <SelectItem value="none">Không thêm playlist</SelectItem>
                  {playlists.map((playlist) => <SelectItem key={playlist.id} value={playlist.id}>{playlist.title}</SelectItem>)}
                </SelectContent>
              </Select>
            </div>
            <div className="grid gap-3 md:grid-cols-3">
              <Toggle label="Made for Kids" checked={form.madeForKids} onChange={(value) => setForm({ ...form, madeForKids: value })} />
              <Toggle label="Notify subscribers" checked={form.notifySubscribers} onChange={(value) => setForm({ ...form, notifySubscribers: value })} />
              <Toggle label="Synthetic media" checked={form.containsSyntheticMedia} onChange={(value) => setForm({ ...form, containsSyntheticMedia: value })} />
            </div>
            <Button className="w-full bg-red-500 text-white hover:bg-red-600" onClick={upload} disabled={loading || !canUpload}>Upload YouTube</Button>
          </Card>

          {result ? (
            <Card className="space-y-2 p-4">
              <h2 className="font-semibold text-emerald-300">Upload result</h2>
              <p className="text-sm">{result.title || form.title}</p>
              {result.url ? <a className="inline-flex items-center gap-2 text-sm text-red-400 underline" href={result.url} target="_blank" rel="noreferrer">Mở video <ExternalLink className="h-3.5 w-3.5" /></a> : null}
              {result.playlistWarning ? <p className="text-xs text-yellow-300">{result.playlistWarning}</p> : null}
            </Card>
          ) : null}
        </div>
      </main>
    </div>
  );
}

function normalizeForm(form: YoutubeUploadForm): YoutubeUploadForm {
  return { ...form, publishAt: form.publishAt ? new Date(form.publishAt).toISOString() : "" };
}

function StatusRow({ label, ok }: { label: string; ok: boolean }) {
  return <div className="flex items-center justify-between rounded-lg border border-border px-3 py-2 text-sm"><span>{label}</span><span className={ok ? "text-emerald-300" : "text-muted-foreground"}>{ok ? <CheckCircle2 className="h-4 w-4" /> : "Chưa có"}</span></div>;
}

function Field(props: { label: string; value: string; type?: string; onChange: (value: string) => void }) {
  return <div><Label>{props.label}</Label><Input className="mt-2" type={props.type ?? "text"} value={props.value} onChange={(event) => props.onChange(event.target.value)} /></div>;
}

function Toggle({ label, checked, onChange }: { label: string; checked: boolean; onChange: (value: boolean) => void }) {
  return <div className="flex items-center justify-between rounded-lg border border-border px-3 py-2"><Label>{label}</Label><Switch checked={checked} onCheckedChange={onChange} /></div>;
}
