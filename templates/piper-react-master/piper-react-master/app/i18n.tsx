export type TranslationKey = keyof typeof translations.en;

type I18nContextValue = {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    setLanguageState(readStoredLanguage() || detectDeviceLanguage());
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = language;
    }
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    return {
      language,
      locale: language === "vi" ? "vi-VN" : "en-US",
      setLanguage(nextLanguage) {
        setLanguageState(nextLanguage);
        if (typeof localStorage !== "undefined") {
          localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
        }
      },
      t(key, values) {
        const template: string = translations[language][key] || translations.en[key];

        if (!values) {
          return template;
        }

        return Object.entries(values).reduce<string>(
          (current, [name, value]) => current.replaceAll(`{${name}}`, String(value)),
          template
        );
      },
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider.");
  }

  return context;
}

function readStoredLanguage(): Language | null {
  if (typeof localStorage === "undefined") {
    return null;
  }

  return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));
}

function detectDeviceLanguage(): Language {
  if (typeof navigator === "undefined") {
    return "en";
  }

  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  return languages.some((language) => normalizeLanguage(language) === "vi") ? "vi" : "en";
}

function normalizeLanguage(language: string | null | undefined): Language | null {
  const normalized = language?.toLowerCase();

  if (!normalized) {
    return null;
  }

  if (normalized.startsWith("vi")) {
    return "vi";
  }

  if (normalized.startsWith("en")) {
    return "en";
  }

  return null;
}

