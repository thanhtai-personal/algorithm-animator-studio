import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import type { Lang } from "@/lib/i18n";
import { PathInput } from "./SettingsFields";
import type { SettingsForm, SettingsFormKey } from "./SettingsTypes";
import { txt } from "./settingsText";

type SettingsDataTabProps = {
  form: SettingsForm;
  lang: Lang;
  selecting: string | null;
  onOpenPath: (targetPath: string) => void;
  onSelectPath: (kind: "directory" | "file", target: SettingsFormKey, title: string) => void;
  onUpdateField: (key: SettingsFormKey, value: string) => void;
};

export function SettingsDataTab(props: SettingsDataTabProps) {
  const vi = props.lang === "vi";

  return (
    <Card>
      <CardHeader>
        <CardTitle>Data</CardTitle>
        <CardDescription>{txt(vi, "Cấu hình nơi lưu dữ liệu được tạo bởi app và thư viện nhạc nền.", "Configure where app-generated data and the background music library are stored.")}</CardDescription>
      </CardHeader>
      <CardContent className="space-y-5">
        <PathInput
          id="server-data-dir"
          label="SERVER_DATA_DIR"
          description={txt(vi, "Thư mục gốc để lưu các file app tạo ra như audio, preview, video và background music đã render.", "Root folder for files generated by the app, including audio, previews, videos, and rendered background music.")}
          lang={props.lang}
          value={props.form.SERVER_DATA_DIR}
          placeholder="server/data"
          busy={props.selecting === "SERVER_DATA_DIR"}
          onChange={(value) => props.onUpdateField("SERVER_DATA_DIR", value)}
          onSelect={() => props.onSelectPath("directory", "SERVER_DATA_DIR", txt(vi, "Chọn thư mục lưu dữ liệu được tạo", "Select the generated data folder"))}
          onOpen={() => props.onOpenPath(props.form.SERVER_DATA_DIR)}
        />
        <PathInput
          id="music-library-dir"
          label="MUSIC_LIBRARY_DIR"
          description={txt(vi, "Thư mục chứa thư viện nhạc nền. Mỗi track nằm trong một folder riêng, kèm License.txt nếu cần ghi credit YouTube.", "Folder containing the background music library. Each track should be in its own folder, with License.txt when YouTube credit is needed.")}
          lang={props.lang}
          value={props.form.MUSIC_LIBRARY_DIR}
          placeholder="C:/Users/.../Music/youtube-audios"
          busy={props.selecting === "MUSIC_LIBRARY_DIR"}
          onChange={(value) => props.onUpdateField("MUSIC_LIBRARY_DIR", value)}
          onSelect={() => props.onSelectPath("directory", "MUSIC_LIBRARY_DIR", txt(vi, "Chọn thư mục thư viện nhạc nền", "Select the background music library folder"))}
          onOpen={() => props.onOpenPath(props.form.MUSIC_LIBRARY_DIR)}
        />
      </CardContent>
    </Card>
  );
}
