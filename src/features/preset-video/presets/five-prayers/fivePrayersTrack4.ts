export const FIVE_PRAYERS_TRACK_4_LYRICS = `
Phúc thật tám mối:

Thứ nhất:
Ai có lòng khó khăn,
ấy là phúc thật,
vì chưng Nước Đức Chúa Trời
là của mình vậy.

Thứ hai:
Ai hiền lành,
ấy là phúc thật,
vì chưng sẽ được đất Đức Chúa Trời
làm của mình vậy.

Thứ ba:
Ai khóc lóc,
ấy là phúc thật,
vì chưng sẽ được an ủi vậy.

Thứ bốn:
Ai khao khát nhân đức trọn lành,
ấy là phúc thật,
vì chưng sẽ được no đủ vậy.

Thứ năm:
Ai thương xót người,
ấy là phúc thật,
vì chưng mình sẽ được thương xót vậy.

Thứ sáu:
Ai giữ lòng sạch sẽ,
ấy là phúc thật,
vì chưng sẽ được thấy mặt
Đức Chúa Trời vậy.

Thứ bảy:
Ai làm cho người hòa thuận,
ấy là phúc thật,
vì chưng sẽ được gọi
là con Đức Chúa Trời vậy.

Thứ tám:
Ai chịu khốn nạn vì đạo ngay,
ấy là phúc thật,
vì chưng Nước Đức Chúa Trời
là của mình vậy.

Con cám ơn Đức Chúa Trời
là Chúa lòng lành vô cùng,

chẳng bỏ con,
chẳng để con không đời đời,

mà lại sinh ra con,
cho con được làm người,

cùng hằng gìn giữ con,
hằng che chở con;

lại cho Ngôi Hai xuống thế làm người,
chuộc tội chịu chết
trên cây Thánh giá vì con,

lại cho con được
đạo thánh Đức Chúa Trời,

cùng chịu nhiều ơn
nhiều phép Hội Thánh nữa,

và đã cho phần xác con
ngày hôm nay, đêm nay,
được mọi sự lành;

lại cứu lấy con
kẻo phải chết tươi
ăn năn tội chẳng kịp.

Vậy các thánh
ở trên nước Thiên đàng
cám ơn Đức Chúa Trời thế nào,

thì con cũng hiệp cùng các thánh
mà dâng cho Chúa,
cùng cám ơn như vậy.

Amen.
`;
